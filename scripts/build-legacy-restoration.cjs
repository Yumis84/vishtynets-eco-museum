// Generate a regular data batch; original binaries stay in the donor repository.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const text=JSON.parse(fs.readFileSync(path.join(root,'data/legacy-restored-priority.json'),'utf8'));
const media=JSON.parse(fs.readFileSync(path.join(root,'data/legacy-restored-media.json'),'utf8'));
const patches=new Map();
for(const entry of text.articles){
  const patch=patches.get(entry.id)||{id:entry.id,content:[],archiveSources:[],archival:true,migrationStatus:'original_text_restored_media_reviewed'};
  if(entry.mode==='append')patch.content.push({type:'heading',text:entry.sectionTitle||entry.sourcePage});
  patch.content.push(...entry.content.filter(b=>b.type!=='gallery'));
  patch.archiveSources.push({repository:text.sourceRepository,commit:text.sourceCommit,path:entry.sourcePage,sha256:entry.sourceSha256});
  patch.sourceLinks=[...(patch.sourceLinks||[]),...(entry.sourceLinks||[])];
  patches.set(entry.id,patch);
}
for(const entry of media.articles){
  const patch=patches.get(entry.id); if(!patch)throw Error('Unknown restored article '+entry.id);
  patch.images=[...(patch.images||[]),...entry.images].filter((image,i,all)=>all.findIndex(x=>x.src===image.src)===i);
  if(!patch.hero&&entry.hero)patch.hero=entry.hero;
}
for(const patch of patches.values()){
  if(patch.images?.length)patch.content.push({type:'gallery'});
  patch.sourceMediaCount=patch.images?.length||0;
  patch.deck=''; // The source text replaces the earlier editorial summary.
  patch.sourceLinks=[...(patch.sourceLinks||[])].filter((link,i,all)=>link.href && all.findIndex(x=>x.href===link.href)===i);
}
const output='// Generated by scripts/build-legacy-restoration.cjs; edit data/legacy-restored-*.json.\n'+
 '(function(){\n\'use strict\';\nconst patches='+JSON.stringify([...patches.values()],null,2)+';\n'+
 'window.applyMuseumLegacyRestorations=function(){\nconst articles=window.MUSEUM_ARTICLES||[];\nfor(const patch of patches){const article=articles.find(a=>a.id===patch.id);if(article)Object.assign(article,patch);}\n};\nwindow.applyMuseumLegacyRestorations();\n})();\n';
fs.writeFileSync(path.join(root,'museum-legacy-restored.js'),output);
console.log('Generated '+patches.size+' restored article patches');
